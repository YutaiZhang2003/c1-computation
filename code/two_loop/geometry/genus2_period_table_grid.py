#!/usr/bin/env python3
"""Prepare deterministic genus-two period-table manifests.

Two designs are supported without evaluating a finite-q period matrix:

* the original invariant-domain atlas-selected theta/glasses union; and
* a forward, scrambled-Sobol grid in plumbing coordinates.  The latter is
  used to extend the glass-channel ``q -> Omega`` table directly.
"""

