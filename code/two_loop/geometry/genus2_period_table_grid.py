Topology = Literal["theta", "glasses"]
SCHEMA_VERSION = 1
USEFUL_REGION_SELECTOR_IMPLEMENTED = True
ATLAS_MODE = "atlas-selected-theta-glasses-union"
FORWARD_GRID_MODE = "glass-forward-q-grid"
THIS_FILE = Path(__file__).resolve()
